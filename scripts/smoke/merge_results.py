"""Merge per-framework smoke results into results/smoke_result.json (task 2.1).

Applies the design's selection rule: a framework is eligible only if every
smoke-test condition passed; among eligible frameworks choose the higher
environment steps/s at the tested parallel count, ties broken toward the one
with a working ONNX export path. Also writes the Markdown block that
scripts/smoke_test.sh places in docs/ENVIRONMENT.md. Exits 1 when no
framework passed.

Usage: merge_results.py <out.json> <out_block.md> <nvsmi_win.txt> <nvsmi_wsl.txt>
                        <command> <commit> <framework.json>...
"""

from __future__ import annotations

import json
import sys

# Conditions that decide eligibility (design "Smoke test"). The ONNX path is
# the tie-breaker only, so it is reported but not required.
REQUIRED = ["nvidia_smi_saved", "gpu_backend", "steps_on_gpu_at_count", "range_rays_every_step",
            "miss_value_proven", "no_self_hits", "physics_finite", "versions_recorded"]


def evaluate(r: dict, nvsmi_ok: bool) -> dict:
    cond = r.setdefault("conditions", {})
    cond["versions_recorded"] = bool(r.get("versions"))
    cond["nvidia_smi_saved"] = nvsmi_ok
    failed = [c for c in REQUIRED if not cond.get(c, False)]
    if "error" in r:
        failed = ["error: " + r["error"]] + failed
    r["passed"] = not failed
    r["first_failing_condition"] = failed[0] if failed else None
    return r


def choose(frameworks: dict) -> str | None:
    eligible = [k for k, r in frameworks.items() if r["passed"]]
    eligible.sort(key=lambda k: (frameworks[k]["env_steps_per_s"],
                                 frameworks[k]["conditions"].get("onnx_export_path", False)), reverse=True)
    return eligible[0] if eligible else None


def markdown(result: dict, nvsmi_win: str, nvsmi_wsl: str) -> str:
    lines = [
        "## M0 smoke test (generated by `scripts/smoke_test.sh`)",
        "",
        f"- Command: `{result['command']}`",
        f"- Commit: `{result['commit']}`; seed {result['seed']} (start poses and wheel commands)",
        f"- Raw result: `results/smoke_result.json`; logs: `docs/evidence/smoke_*.log`",
        f"- Chosen framework: **{result['chosen_framework']}** ({result['selection_rule']})",
        "",
        "| Framework | Passed | First failing condition | Parallel envs | Steps measured | Env steps/s | "
        "Range_Rays shape per step | Miss value | ONNX path (max abs diff) |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for k, r in result["frameworks"].items():
        sps = r.get("env_steps_per_s")
        onnx = r.get("onnx", {})
        lines.append(
            f"| {k} ({r.get('implementation', '')}) | {r['passed']} | {r['first_failing_condition'] or '-'} | "
            f"{r.get('num_envs')} | {r.get('n_steps')} x 3 reps | {f'{sps:,.0f}' if sps else '-'} | "
            f"{r.get('sensordata_shape_per_step')} (incl. 1 miss probe) | {r.get('miss_value_observed')} | "
            f"{onnx.get('max_abs_diff', onnx.get('error', '-'))} |")
    lines += ["", "Per-condition results:", ""]
    for k, r in result["frameworks"].items():
        conds = ", ".join(f"{c}={v}" for c, v in r.get("conditions", {}).items())
        lines.append(f"- {k}: {conds}")
    lines += ["", "Versions (package-manager query, `uv pip freeze` in `docs/evidence/freeze_<env>.txt`):", ""]
    for k, r in result["frameworks"].items():
        vers = ", ".join(f"{p}=={v}" for p, v in r.get("versions", {}).items())
        lines.append(f"- {k}: {vers}")
        if k == "mjx":
            envs = ", ".join(f"`{k}={v}`" for k, v in r.get("env", {}).items())
            lines.append(f"  - {envs} during the MJX smoke run; devices {r.get('jax_devices')}")
        else:
            lines.append(f"  - warp device {r.get('warp_device')}, torch CUDA {r.get('torch_cuda')} "
                         f"({r.get('torch_device_name')})")
    lines += ["", "### nvidia-smi on Windows", "", "```", nvsmi_win.rstrip(), "```", "",
              "### nvidia-smi inside WSL (Ubuntu-24.04)", "", "```", nvsmi_wsl.rstrip(), "```"]
    return "\n".join(lines) + "\n"


def main(out_json: str, out_md: str, nvsmi_win: str, nvsmi_wsl: str, command: str, commit: str,
         *paths: str) -> int:
    win = open(nvsmi_win).read()
    wsl = open(nvsmi_wsl).read()
    nvsmi_ok = "RTX 3080" in win and "RTX 3080" in wsl
    frameworks = {}
    for p in paths:
        with open(p) as f:
            r = evaluate(json.load(f), nvsmi_ok)
        frameworks[r["framework"]] = r
    result = {
        "chosen_framework": choose(frameworks),
        "selection_rule": "eligible = all required conditions pass; choose max env_steps_per_s at the "
                          "tested parallel count; tie -> working ONNX export path",
        "required_conditions": REQUIRED,
        "command": command,
        "commit": commit,
        "seed": 0,
        "frameworks": frameworks,
    }
    with open(out_json, "w") as f:
        json.dump(result, f, indent=2)
    with open(out_md, "w") as f:
        f.write(markdown(result, win, wsl))
    for k, r in frameworks.items():
        print(f"{k}: passed={r['passed']} first_failing={r['first_failing_condition']} "
              f"steps/s={r.get('env_steps_per_s')}")
    print(f"chosen: {result['chosen_framework']}")
    return 0 if result["chosen_framework"] else 1


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:]))
