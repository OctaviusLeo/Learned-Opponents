#!/usr/bin/env bash
# Create the project environment ~/.venvs/learned-opponents for the framework
# chosen in M0 (mjlab / MuJoCo Warp), install this repository in editable
# mode, and freeze the exact versions to requirements-gpu.lock (task 2.2).
set -euo pipefail
UV="${UV:-$HOME/.local/bin/uv}"
REPO="$(cd "$(dirname "$0")/.." && pwd)"
VENV="$HOME/.venvs/learned-opponents"
[ -x "$VENV/bin/python" ] || "$UV" venv --python 3.12 "$VENV"
cd "$REPO"
"$UV" pip install --python "$VENV/bin/python" -e ".[gpu,test]"
{
  echo "# uv pip freeze of ~/.venvs/learned-opponents (generated by scripts/make_project_venv.sh)"
  "$UV" pip freeze --python "$VENV/bin/python" --exclude-editable
} > requirements-gpu.lock
"$VENV/bin/python" -c "import learned_opponents, mjlab, mujoco_warp, torch, rsl_rl; print('ok', torch.__version__, torch.cuda.is_available())"
