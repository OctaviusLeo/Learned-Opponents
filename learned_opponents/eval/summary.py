"""Generate ``results/summary.md`` from the raw result files (never hand-edited).

    python -m learned_opponents.eval.summary

Reads ``results/eval/*.json`` (written by the evaluation, robustness, pilot,
and transfer commands) and renders every section that has data. Each section
carries the generating command, seeds, and full commit hash next to its
numbers. Imports only numpy and the standard library.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Mapping

from learned_opponents.eval import metrics as M

REPO = Path(__file__).resolve().parents[2]
EVAL_DIR = REPO / "results" / "eval"
SUMMARY = REPO / "results" / "summary.md"

HEADER = """# Results summary

Generated by `python -m learned_opponents.eval.summary` from `results/eval/*.json`; do not edit by
hand. Rates are Success_Rate / Collision_Rate with 95% Wilson intervals; Time_To_Goal is the mean over
successful episodes with a 95% Student-t interval. Episodes are pooled across the 3 training seeds per
variant; the pooled interval covers episode sampling only, so each seed's own rate is listed too.
"""


def load(name: str, eval_dir: Path = EVAL_DIR) -> dict[str, Any] | None:
    p = eval_dir / name
    if not p.is_file():
        return None
    with open(p, encoding="utf-8") as f:
        return json.load(f)


def seed_metrics(d: Mapping[str, Any], dt: float) -> dict[str, Any]:
    return {"success": M.wilson(d["success"], d["n"]), "collision": M.wilson(d["collision"], d["n"]),
            "timeout": d["timeout"], "n": d["n"],
            "ttg": M.mean_t_ci([s * dt for s in d["success_steps"]])}


def pooled_metrics(seeds: Mapping[str, Mapping[str, Any]], dt: float) -> dict[str, Any]:
    ds = list(seeds.values())
    steps = [s for d in ds for s in d["success_steps"]]
    return {"success": M.pooled([d["success"] for d in ds], [d["n"] for d in ds]),
            "collision": M.pooled([d["collision"] for d in ds], [d["n"] for d in ds]),
            "timeout": sum(d["timeout"] for d in ds), "n": sum(d["n"] for d in ds),
            "ttg": M.mean_t_ci([s * dt for s in steps])}


def nominal_section(r: Mapping[str, Any]) -> str:
    dt = float(r["control_dt_s"])
    seeds = r["seeds"]
    pool = pooled_metrics(seeds, dt)
    target = float(r["nominal_success_target"])
    met = pool["success"].rate >= target
    lines = [f"## Nominal evaluation: {r['variant']}", "",
             f"- Command: `{r['command']}`",
             f"- Commit: `{r['commit']}`",
             f"- Training seeds: {', '.join(seeds)}; training commits: "
             + ", ".join(f"seed {s} `{d['train_commit']}`" for s, d in seeds.items()),
             f"- Evaluation seed {r['eval_seed']}, {r['episodes_per_seed']} episodes per training seed, "
             "deterministic actions, nominal domain parameters",
             "", "| Seed | Episodes | Success_Rate [95% CI] | Collision_Rate [95% CI] | Timeouts | "
             "Mean Time_To_Goal [95% CI] |", "| --- | --- | --- | --- | --- | --- |"]
    for s, d in seeds.items():
        m = seed_metrics(d, dt)
        lines.append(f"| {s} | {m['n']} | {M.fmt_rate(m['success'])} | {M.fmt_rate(m['collision'])} | "
                     f"{m['timeout']} | {M.fmt_mean(m['ttg'])} |")
    lines.append(f"| pooled | {pool['n']} | {M.fmt_rate(pool['success'])} | {M.fmt_rate(pool['collision'])} | "
                 f"{pool['timeout']} | {M.fmt_mean(pool['ttg'])} |")
    lines += ["", f"Target `nominal_success_target` = {target:.2f}: pooled Success_Rate "
              f"{pool['success'].rate:.3f} -> **{'met' if met else 'missed'}**."]
    if r.get("repeats"):
        reps = r["repeats"]
        tol = max(v["max_abs_rate_diff"] for v in reps.values())
        k = len(next(iter(reps.values()))["success_counts"])
        lines.append(f"Evaluation reproducibility: each checkpoint was evaluated {k} times on the same "
                     f"evaluation seed (the table shows the first). Success counts per repeat: "
                     + "; ".join(f"seed {s}: {v['success_counts']}" for s, v in reps.items())
                     + f". Measured evaluation tolerance (largest spread in a seed's Success_Rate): "
                     f"**{tol:.4f}**. Repeats are not bit-identical because MuJoCo Warp accumulates with "
                     "floating-point atomics, so borderline episodes can flip.")
    return "\n".join(lines) + "\n"


def pilot_section(r: Mapping[str, Any]) -> str:
    lines = ["## Training reproducibility (pilot, never reported as a result)", "",
             f"- Command: `{r['command']}`", f"- Commit: `{r['commit']}`",
             f"- Pilot seed {r['seed']} trained twice with the frozen config; each run evaluated at nominal "
             f"parameters on evaluation seed {r['eval_seed']} ({r['episodes']} episodes)", "",
             "| Run | Success_Rate [95% CI] | Wall time |", "| --- | --- | --- |"]
    for name, d in r["runs"].items():
        lines.append(f"| {name} | {M.fmt_rate(M.wilson(d['success'], d['n']))} | {d['wall_min']:.1f} min |")
    lines += ["", f"Measured training reproducibility tolerance on this GPU (absolute difference in nominal "
              f"Success_Rate between the two runs): **{r['tolerance']:.3f}**."]
    return "\n".join(lines) + "\n"


def pilot_curve_section(r: Mapping[str, Any]) -> str:
    lines = ["## Training budget selection (pilot, never reported as a result)", "",
             f"- Command: `{r['command']}` after `{r['training_command']}`",
             f"- Commit: `{r['commit']}` (pilot trained at `{r['train_commit']}`)",
             f"- Pilot seed {r['seed']}, baseline variant; each checkpoint evaluated at nominal parameters on "
             f"{r['episodes']} layouts from the pilot seed's evaluation stream (not the reported evaluation seed).",
             f"- Rule: {r['rule']}", "",
             "| Env steps | Wall time | Success_Rate [95% CI] | Collisions | Timeouts |", "| --- | --- | --- | --- | --- |"]
    for p in r["points"]:
        lines.append(f"| {p['env_steps']:,} | {p['elapsed_min']:.1f} min | "
                     f"{M.fmt_rate(M.wilson(p['success'], p['n']))} | {p['collision']} | {p['timeout']} |")
    lines += ["", f"Chosen `training_budget_steps` = **{r['chosen_env_steps']:,}** (Success_Rate "
              f"{r['chosen_success_rate']:.3f}; best {r['best_success_rate']:.3f}; target "
              f"{'met' if r['meets_target'] else 'not met'})."]
    if r.get("history"):
        lines.append("Earlier pilot evidence (stopped runs and why): " + ", ".join(f"`{h}`" for h in r["history"]))
    return "\n".join(lines) + "\n"


def render(eval_dir: Path = EVAL_DIR) -> str:
    parts = [HEADER]
    for variant in ("baseline", "randomized"):
        r = load(f"nominal_{variant}.json", eval_dir)
        if r:
            parts.append(nominal_section(r))
    r = load("pilot_curve.json", eval_dir)
    if r:
        parts.append(pilot_curve_section(r))
    r = load("pilot_reproducibility.json", eval_dir)
    if r:
        parts.append(pilot_section(r))
    from learned_opponents.eval import summary_sections

    for fn in summary_sections.SECTIONS:
        text = fn(eval_dir)
        if text:
            parts.append(text)
    return "\n".join(parts)


def write_summary(path: Path = SUMMARY, eval_dir: Path = EVAL_DIR) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(eval_dir))
    return path


if __name__ == "__main__":
    print(write_summary())
